#!/usr/bin/env python3
"""Circuit inputs from the synthetic taps: <pkg>/Prover.toml (from the package's first kind) and
<pkg>/src/tests/vectors.nr (every kind of the package)."""

import json
import os
from typing import Any, NoReturn

import verify_emv_reference as vc
from gen_synthetic import FIXTURES, KINDS

ROOT = os.path.dirname(FIXTURES)
CA_KEYS = os.path.join(FIXTURES, "test-ca-keys.json")
TODAY = 2609  # YYMM, pinned so the committed outputs don't change every month
SCOPE = 0x5C09E  # any field element; the emv crate derives real ones

LIMB_BITS = 120
MAX_STATIC_DATA_LEN = 256  # MAX_STATIC_DATA_LEN of both circuits

Inputs = dict[str, Any]


def limbs(modulus: bytes) -> list[int]:
    """120-bit little-endian limbs."""
    n, count = int.from_bytes(modulus, "big"), (len(modulus) * 8 + LIMB_BITS - 1) // LIMB_BITS
    return [(n >> (LIMB_BITS * i)) & ((1 << LIMB_BITS) - 1) for i in range(count)]


def fail(name: str, what: str) -> NoReturn:
    raise SystemExit(f"fixtures/{name}.json: {what} does not verify")


def circuit_inputs(name: str, capks: vc.CAKeys) -> Inputs:
    pkg = KINDS[name]["package"]
    doc = json.load(open(os.path.join(FIXTURES, name + ".json")))
    els = vc.elements(doc)

    def h(tag: str) -> bytes:
        return vc.h2b(els.get(tag, {}).get("value"))

    rid = doc["selectedAid"][:10]
    ca, issuer = b"", None
    for exp, mod, _ in capks.get((rid, els["8F"]["value"]), []):
        issuer, _ = vc.verify_issuer_cert(h("90"), mod, exp, h("92"), h("9F32"))
        if issuer:
            ca = mod
            break
    if not issuer:
        fail(name, "issuer certificate")
    static = vc.static_data_to_authenticate(doc, els)
    icc, _ = vc.verify_icc_cert(h("9F46"), issuer["modulus"], issuer["exponent"], h("9F48"), h("9F47"), static)
    if not icc or not icc["hash_ok"]:
        fail(name, "ICC certificate")

    t = doc["terminal"]
    un, amount, currency = (bytes(t[k]) for k in ("unpredictableNumber", "amountAuthorised", "currencyCode"))
    td = un + amount + currency + h("9F69") if pkg == "visa_fdda" else un
    sd, _ = vc.verify_sdad(h("9F4B"), icc["modulus"], icc["exponent"], [("", td)])
    if not sd or not sd["matched"]:
        fail(name, "signed dynamic data")

    x = {
        "ca_modulus": limbs(ca),
        "nonce": list(un),
        "issuer_cert": list(h("90")),
        "issuer_exponent": h("9F32")[0],
        "icc_cert": list(h("9F46")),
        "icc_exponent": h("9F47")[0],
        "sdad": list(h("9F4B")),
    }
    assert len(static) <= MAX_STATIC_DATA_LEN
    x["static_data"] = {"storage": list(static) + [0] * (MAX_STATIC_DATA_LEN - len(static)), "len": len(static)}
    if pkg == "visa_fdda":
        x.update(amount=list(amount), currency=list(currency), card_auth_data=list(h("9F69")))
    else:
        x.update(issuer_remainder=list(h("92")))
    x["today"] = TODAY
    x["scope"] = SCOPE
    x["icc_modulus"] = list(icc["modulus"])
    return x


def toml_value(v: Any) -> str:
    if isinstance(v, list):
        return "[" + ", ".join(f'"{i}"' if i >= 1 << 63 else str(i) for i in v) + "]"
    return f'"{v}"' if isinstance(v, int) and v >= 1 << 63 else str(v)


def to_toml(x: Inputs) -> str:
    lines, tables = [], []
    for k, v in x.items():
        if isinstance(v, dict):
            tables.append(f"\n[{k}]\n" + "\n".join(f"{a} = {toml_value(b)}" for a, b in v.items()))
        else:
            lines.append(f"{k} = {toml_value(v)}")
    return "\n".join(lines) + "".join(tables) + "\n"


def noir_value(v: Any) -> str:
    if isinstance(v, dict):
        return f"BoundedVec::from_parts({noir_value(v['storage'])}, {v['len']})"
    if isinstance(v, list):
        return "[" + ", ".join(hex(i) for i in v) + "]"
    return hex(v)


def to_noir(cards: list[tuple[str, Inputs, list[int]]]) -> str:
    """CARDS and, per card, ICC_MODULI: the modulus its certificate binds."""
    n, width = len(cards), len(cards[0][2])
    out = [
        "// Generated by scripts/gen_circuit_inputs.py from the synthetic taps in fixtures/.",
        "use crate::Inputs;",
        "",
        f"pub global ICC_MODULI: [[u8; {width}]; {n}] = [",
    ]
    out += [f"    // {name}\n    {noir_value(m)}," for name, _, m in cards]
    out += ["];", "", f"pub global CARDS: [Inputs; {n}] = ["]
    for name, x, _ in cards:
        out += [f"    // {name}", "    Inputs {"]
        out += [f"        {k}: {noir_value(v)}," for k, v in x.items()]
        out += ["    },"]
    out += ["];"]
    return "\n".join(out) + "\n"


def struct_fields(pkg: str) -> list[str]:
    main_nr = open(os.path.join(ROOT, pkg, "src", "main.nr")).read()
    body = main_nr.split("pub struct Inputs {")[1].split("}")[0]
    return [line.split(":")[0].strip().removeprefix("pub ") for line in body.strip().splitlines()]


def main() -> None:
    capks = vc.load_CA_pubkeys(CA_KEYS)
    packages: dict[str, list[tuple[str, Inputs, list[int]]]] = {}
    for name, kind in KINDS.items():
        x = circuit_inputs(name, capks)
        icc_modulus = x.pop("icc_modulus")
        packages.setdefault(kind["package"], []).append((name, x, icc_modulus))
    for pkg, cards in packages.items():
        open(os.path.join(ROOT, pkg, "Prover.toml"), "w").write(to_toml(cards[0][1]))
        ordered = [(name, {k: x[k] for k in struct_fields(pkg)}, m) for name, x, m in cards]
        open(os.path.join(ROOT, pkg, "src", "tests", "vectors.nr"), "w").write(to_noir(ordered))
        print(f"wrote {pkg}/Prover.toml, {pkg}/src/tests/vectors.nr ({', '.join(name for name, _, _ in cards)})")


if __name__ == "__main__":
    main()
